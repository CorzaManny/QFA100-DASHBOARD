// SimBrief: plan the next sector and import the latest OFP.

import { state } from '../store.js';
import { esc, zulu, zdate, ago, icon, rerender } from '../ui.js';
import { upcomingSector, currentSector, simbriefPlanUrl, fetchOfp } from '../ops.js';

let busy = false;
let error = '';

const hhmm = (secs) =>
  secs == null ? '—' : `${String(Math.floor(secs / 3600)).padStart(2, '0')}:${String(Math.floor((secs % 3600) / 60)).padStart(2, '0')}`;

function row(label, value) {
  return `<div class="kv"><span>${label}</span><strong>${value}</strong></div>`;
}

function ofpCard(o) {
  const u = esc(o.units.toUpperCase());
  const w = (v) => (v == null ? '—' : `${v.toLocaleString('en-AU')} ${u}`);
  return `
    <section class="card">
      <div class="card-head"><div class="tiny">SIMBRIEF OFP · ${esc(o.callsign)}</div>
        <span class="badge ok">IMPORTED</span></div>
      <div class="route">
        <div><div class="apt">${esc(o.dep)}</div><div class="tiny">${o.depRwy ? `RWY ${esc(o.depRwy)}` : ''}</div></div>
        <div class="route-mid">${icon('plane', 'plane')}<div class="tiny">${hhmm(o.ete)} ENROUTE</div></div>
        <div class="right"><div class="apt">${esc(o.arr)}</div><div class="tiny">${o.arrRwy ? `RWY ${esc(o.arrRwy)}` : ''}</div></div>
      </div>
      <pre class="metar">${esc(o.route || 'No route in OFP')}</pre>
      <div class="kvs">
        ${row('Aircraft', esc([o.acft, o.reg].filter(Boolean).join(' · ') || '—'))}
        ${row('Alternate', esc(o.altn || '—'))}
        ${row('Cruise', o.cruise ? `FL${Math.round(o.cruise / 100)}` : '—')}
        ${row('Cost index', esc(o.costIndex || '—'))}
        ${row('Scheduled out', o.schedOut ? `${zdate(o.schedOut)} ${zulu(o.schedOut)}` : '—')}
        ${row('Passengers', o.pax ?? '—')}
      </div>
      <h3>Fuel</h3>
      <div class="kvs">
        ${row('Block', w(o.blockFuel))}${row('Trip', w(o.tripFuel))}${row('Taxi', w(o.taxiFuel))}
        ${row('Alternate', w(o.altnFuel))}${row('Reserve', w(o.reserveFuel))}
      </div>
      <h3>Weights</h3>
      <div class="kvs">${row('ZFW', w(o.zfw))}${row('TOW', w(o.tow))}${row('LDW', w(o.ldw))}</div>
      ${o.pdf ? `<a class="btn ghost" href="${esc(o.pdf)}" target="_blank" rel="noopener">Open full OFP (PDF) ${icon('external')}</a>` : ''}
      <div class="tiny">Imported ${ago(o.fetchedAt)}${o.generated ? ` · generated ${zdate(o.generated)} ${zulu(o.generated)}` : ''}</div>
    </section>`;
}

export function render() {
  const target = upcomingSector() || currentSector();
  const id = state.profile.simbrief.trim();
  const o = state.ofp;
  const mismatch = o && target && (o.dep !== target.dep || o.arr !== target.arr);
  return `
    <div class="page-head"><h1>SimBrief Dispatch</h1></div>
    <section class="card">
      <h2>1. Plan the flight</h2>
      ${
        target
          ? `<p class="note">Opens SimBrief with <strong>${esc(target.dep)} → ${esc(target.arr)}</strong> (${esc(target.flight)}, ${esc(state.profile.aircraft)}) filled in.</p>
             <a class="btn primary" href="${esc(simbriefPlanUrl(target))}" target="_blank" rel="noopener">Plan in SimBrief ${icon('external')}</a>`
          : '<p class="note">Add a sector to the schedule and it will be prefilled here.</p>'
      }
    </section>
    <section class="card">
      <h2>2. Import your latest OFP</h2>
      ${
        id
          ? `<p class="note">Fetches the most recent flight plan generated by SimBrief user <strong>${esc(id)}</strong>.</p>
             <button class="btn primary" data-act="fetch" ${busy ? 'disabled' : ''}>${busy ? 'Importing…' : 'Import latest OFP'}</button>`
          : '<p class="note">Add your SimBrief username or Pilot ID in Settings to import flight plans.</p><a class="btn ghost" href="#/settings">Open Settings</a>'
      }
      ${error ? `<p class="note warn">${icon('alert')} ${esc(error)}</p>` : ''}
      ${mismatch ? `<p class="note warn">${icon('alert')} This OFP is ${esc(o.dep)} → ${esc(o.arr)}, not the next sector (${esc(target.dep)} → ${esc(target.arr)}).</p>` : ''}
    </section>
    ${o ? ofpCard(o) : ''}`;
}

export const actions = {
  async fetch() {
    if (busy) return;
    busy = true;
    error = '';
    rerender();
    try {
      await fetchOfp();
    } catch (err) {
      error = err.message;
    }
    busy = false;
    if (location.hash.startsWith('#/dispatch')) rerender();
  },
};
