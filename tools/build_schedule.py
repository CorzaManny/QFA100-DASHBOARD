"""Rebuild js/data/schedule.js from the official WorldFlight schedule page.

Usage:
  curl -sL https://planning.worldflight.center/schedule -o schedule.html
  python3 tools/build_schedule.py schedule.html 2026 js/data/schedule.js

The page publishes a two-hour departure window per sector rather than a fixed
time. Each sector's std is the middle of that window, sta is std + block time,
and `window` is the minutes either side of std that the window allows.
"""
import html
import json
import re
import sys
import urllib.parse
from datetime import datetime, timedelta, timezone

page_path, year, out_path = sys.argv[1], int(sys.argv[2]), sys.argv[3]
page = open(page_path, encoding="utf-8").read()
MONTHS = "Jan Feb Mar Apr May Jun Jul Aug Sep Oct Nov Dec".split()


def minutes(hhmm):
    h, m = hhmm.split(":")
    return int(h) * 60 + int(m)


sectors = []
prev_std = None
for row in re.findall(r"<tr class=\"[^\"]*\">(.*?)</tr>", page, re.S):
    btn = re.search(
        r'data-from="(\w{4})" data-to="(\w{4})" data-wf="(\w+)" data-date="([^"]+)" data-dep="(\d\d:\d\d)" data-block="(\d\d:\d\d)"',
        row,
    )
    if not btn:
        continue
    dep, arr, wf, date, dep_time, block = btn.groups()
    day, month = re.search(r"(\d+)\w* (\w{3})", date).groups()
    start, end = re.search(r'window-tt">(\d\d:\d\d)\D(\d\d:\d\d)', row).groups()
    half = ((minutes(end) - minutes(start)) % 1440) // 2

    # data-date and data-dep describe the middle of the window (the visible Date
    # column shows the day the window opens, which can be the day before).
    std = datetime(year, MONTHS.index(month) + 1, int(day), tzinfo=timezone.utc) + timedelta(minutes=minutes(dep_time))
    assert prev_std is None or std > prev_std, (wf, std, prev_std)
    prev_std = std

    route = ""
    link = re.search(r'dispatch\.simbrief\.com/options/custom\?([^"]+)"', row)
    if link:
        route = urllib.parse.parse_qs(html.unescape(link.group(1))).get("route", [""])[0]

    sectors.append(
        {
            "flight": wf,
            "dep": dep,
            "arr": arr,
            "std": std.strftime("%Y-%m-%dT%H:%M:00.000Z"),
            "sta": (std + timedelta(minutes=minutes(block))).strftime("%Y-%m-%dT%H:%M:00.000Z"),
            "window": half,
            "route": route,
        }
    )

with open(out_path, "w", encoding="utf-8") as f:
    f.write("// Official WorldFlight %d schedule, from https://planning.worldflight.center/schedule\n" % year)
    f.write("// Generated by tools/build_schedule.py. Do not edit by hand; re-run the script instead.\n")
    f.write("// std is the middle of the published departure window; window is minutes either side.\n\n")
    f.write("export const OFFICIAL_SCHEDULE = [\n")
    for s in sectors:
        f.write("  " + json.dumps(s, ensure_ascii=False) + ",\n")
    f.write("];\n")
print(len(sectors), "sectors", sectors[0]["std"], "->", sectors[-1]["sta"])
